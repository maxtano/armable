/** Generates the compact MAVLink message table used in the browser from mavlink-mappings' definitions. */
import { writeFileSync } from 'node:fs';
import { minimal, common, standard, ardupilotmega } from 'mavlink-mappings';

const wanted = [
  'HEARTBEAT', 'SYS_STATUS', 'SYSTEM_TIME', 'PARAM_REQUEST_READ', 'PARAM_REQUEST_LIST', 'PARAM_VALUE', 'PARAM_SET',
  'GPS_RAW_INT', 'SCALED_IMU', 'RAW_IMU', 'SCALED_PRESSURE', 'ATTITUDE', 'GLOBAL_POSITION_INT', 'RC_CHANNELS_RAW',
  'SERVO_OUTPUT_RAW', 'MISSION_REQUEST_LIST', 'MISSION_COUNT', 'MISSION_CURRENT', 'MISSION_ACK', 'MISSION_REQUEST_INT',
  'MISSION_ITEM_INT', 'RC_CHANNELS', 'VFR_HUD', 'COMMAND_INT', 'COMMAND_LONG', 'COMMAND_ACK', 'HIGHRES_IMU',
  'LOG_REQUEST_LIST', 'LOG_ENTRY', 'LOG_REQUEST_DATA', 'LOG_DATA', 'LOG_REQUEST_END', 'POWER_STATUS', 'ALTITUDE',
  'BATTERY_STATUS', 'AUTOPILOT_VERSION', 'MEMINFO', 'MAG_CAL_PROGRESS', 'MAG_CAL_REPORT', 'EKF_STATUS_REPORT',
  'VIBRATION', 'HOME_POSITION', 'EXTENDED_SYS_STATE', 'STATUSTEXT', 'ESC_TELEMETRY_1_TO_4', 'ESC_STATUS', 'ESC_INFO',
  'ACTUATOR_OUTPUT_STATUS', 'TIMESYNC', 'PING', 'MESSAGE_INTERVAL', 'ESTIMATOR_STATUS', 'OPEN_DRONE_ID_BASIC_ID',
];
const registry = { ...minimal.REGISTRY, ...standard.REGISTRY, ...common.REGISTRY, ...ardupilotmega.REGISTRY } as Record<string, any>;
const byName = new Map(Object.values(registry).map((c: any) => [c.MSG_NAME, c]));
const rows: string[] = [];
for (const name of wanted) {
  const c = byName.get(name);
  if (!c) { console.error(`skip ${name}: not in mappings`); continue; }
  const fields = c.FIELDS.map((f: any) => {
    const array = f.type.endsWith('[]');
    const type = f.type.replace('[]', '').replace('_mavlink_version', '').replace('_t', '');
    return `['${f.source}','${type}',${f.offset},${array ? f.length : 0}${f.extension ? ',1' : ''}]`;
  });
  rows.push(`  ${name}: { id: ${c.MSG_ID}, crc: ${c.MAGIC_NUMBER}, len: ${c.PAYLOAD_LENGTH}, fields: [${fields.join(',')}] },`);
}
writeFileSync(new URL('../src/device/mavlink/messages.ts', import.meta.url),
`// Generated by scripts/gen-mavlink.ts from mavlink-mappings. Do not edit by hand.
// Field tuple: [name, type, payload offset, array length (0 = scalar), extension flag].
export type FieldDef = readonly [name: string, type: string, offset: number, array: number, extension?: number];
export interface MessageDef { id: number; crc: number; len: number; fields: readonly FieldDef[] }
export const MESSAGES = {
${rows.join('\n')}
} as const satisfies Record<string, MessageDef>;
export type MessageName = keyof typeof MESSAGES;
`);
console.log(`wrote ${rows.length} messages`);
